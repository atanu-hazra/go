package main

// 'fmt' stands for Format package: implements formatted I/O functions (like Println, Printf)
import "fmt"

// main() is the mandatory entry point of any standalone executable Go program.
// It takes no arguments and returns no value.
func main() {
	// fmt.Println prints text to the standard output followed by a new line.
	fmt.Println("Hello World!") // output: Hello World!
}